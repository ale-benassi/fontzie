import { createRequire } from "node:module";
import { readFile, writeFile, mkdir } from "node:fs/promises";

const require = createRequire(import.meta.url);
const output = new URL("../public/fonts/", import.meta.url);
await mkdir(output, { recursive: true });
const families = ["inter", "jetbrains-mono"];
const styles = await Promise.all(
  families.map(async (family) => {
    const packageName = `@fontsource-variable/${family}`;
    const css = await readFile(
      require.resolve(`${packageName}/wght.css`),
      "utf8",
    );
    // A packaged stylesheet keeps URLs on the extension origin in both dev
    // and production, retaining every Unicode subset without base64 expansion.
    const assets = await Promise.all(
      [...css.matchAll(/url\(\.\/files\/([^)]+)\)/g)].map(
        async ([url, file]) => {
          const bytes = await readFile(
            require.resolve(`${packageName}/files/${file}`),
          );
          await writeFile(new URL(file, output), bytes);
          return [url, `url("./${file}")`];
        },
      ),
    );
    return assets.reduce(
      (result, [url, data]) => result.replace(url, data),
      css,
    );
  }),
);

await writeFile(
  new URL("ui-fonts.css", output),
  "/* Generated by npm run fonts:generate from Fontsource wght.css files.\n" +
    " * Preserve font weights and Unicode ranges; licenses: public/licenses/THIRD-PARTY.txt. */\n" +
    styles.join("\n\n") +
    "\n",
);
